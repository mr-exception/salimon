import { test, expect } from '@playwright/test'
import { boot, walkTo, walkTicks } from './worldJourney'

test('FLIGHT-838 production lifecycle, disconnected interior, save/reload and validated return', async ({page},info)=>{
 test.setTimeout(240000)
 await boot(page,'?flightFixture=1')
 const main=page.locator('main'), ship=async()=>JSON.parse((await main.getAttribute('data-ship'))!)
 expect((await ship()).mode).toBe('grounded')
 await page.screenshot({path:info.outputPath('grounded.png')})
 for(const p of [[-2,3],[-2,7]])await walkTo(page,p,'planet:fixture',true)
 for(const p of [[0,7],[0,2],[0,.45],[1.35,.45],[1.35,-1.65],[0,-1.65],[0,-3.1]])await walkTo(page,p,'ship:scout',true)
 await page.keyboard.press('e');await page.clock.runFor(64)
 const deniedShip=await ship()
 await page.getByRole('button',{name:'begin-takeoff',exact:true}).click()
 expect(await ship()).toEqual(deniedShip)
 await expect(page.getByRole('status').filter({hasText:/Close the aft boarding door/})).toBeVisible()
 await page.screenshot({path:info.outputPath('open-door-launch-denial.png')})
 await page.getByRole('button',{name:'Exit cockpit'}).click();await page.clock.runFor(64)
 for(const p of [[0,-1.65],[1.35,-1.65],[1.35,.45],[0,.45],[0,2],[0,4.7]])await walkTo(page,p,'ship:scout',true)
 await page.keyboard.press('e');await page.clock.runFor(32)
 for(const p of [[0,2],[0,.45],[1.35,.45],[1.35,-1.65],[0,-1.65],[0,-3.1]])await walkTo(page,p,'ship:scout',true)
 await page.keyboard.press('e');await page.clock.runFor(64)
 await expect(page.locator('.panoramic')).toBeVisible()
 const view=await page.locator('.panoramic').getAttribute('data-observation'), before=await ship()
 const backend=await page.locator('canvas').evaluate(c=>{const gl=(c as HTMLCanvasElement).getContext('webgl2')!,ext=gl.getExtension('WEBGL_debug_renderer_info')!;return gl.getParameter(ext.UNMASKED_RENDERER_WEBGL)})
 await page.screenshot({path:info.outputPath('grounded-cockpit.png')})
 await page.getByRole('button',{name:'begin-takeoff',exact:true}).click()
 await page.getByRole('button',{name:'finish-takeoff',exact:true}).click()
 await page.clock.runFor(64)
 expect((await ship()).mode).toBe('flying');expect((await ship()).position).toEqual(before.position)
 expect(await page.locator('.panoramic').getAttribute('data-observation')).toBe(view)
 await page.screenshot({path:info.outputPath('flight-cockpit.png')})
 await page.getByRole('button',{name:'Exit cockpit'}).click();await page.clock.runFor(64)
 await expect(page.locator('[data-entity][data-frame="planet:fixture"]')).toHaveCount(0)
 for(const p of [[0,-1.65],[1.35,-1.65],[1.35,.45],[0,.45],[0,2],[0,4.85]])await walkTo(page,p,'ship:scout',true)
 await page.keyboard.press('e');await page.clock.runFor(32)
 await expect(page.getByRole('status').filter({hasText:/Airlock locked/})).toBeVisible()
 await expect(page.locator('[data-entity="scout:entry"]')).toHaveAttribute('data-door-state','closed')
 await walkTicks(page,'s',20)
 await expect(page.getByRole('status').filter({hasText:/Airlock locked/})).toBeVisible()
 await expect(page.getByRole('img',{name:'Strict overhead Scout interior in flight'})).toBeVisible()
 expect(await page.locator('.top-down-stage').evaluate(e=>getComputedStyle(e).backgroundColor)).not.toBe('rgb(181, 165, 139)')
 await page.screenshot({path:info.outputPath('flight-interior.png')})
 await page.evaluate(()=>window.dispatchEvent(new Event('pagehide')))
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('salimon:expedition:v1')!))
 expect(saved.version).toBe(10);expect(saved.scout.binding).toBeNull()
 await page.reload();await page.clock.runFor(64)
 await expect(main).toHaveAttribute('data-player-mode','standing')
 expect((await ship()).mode).toBe('flying');expect((await ship()).position).toEqual(saved.scout.ship.position)
 await expect(page.locator('[data-entity][data-frame="planet:fixture"]')).toHaveCount(0)
 // A reset/scene mount never reattaches the old site. A real live seat is required.
 await page.getByRole('button',{name:'begin-landing',exact:true}).click()
 expect((await ship()).mode).toBe('flying')
 for(const p of [[0,2],[0,.45],[1.35,.45],[1.35,-1.65],[0,-1.65],[0,-3.1]])await walkTo(page,p,'ship:scout',true)
 await page.keyboard.press('e');await page.clock.runFor(64)
 await page.getByRole('button',{name:'begin-landing',exact:true}).click()
 await page.getByRole('button',{name:'finish-landing',exact:true}).click()
 await page.getByRole('button',{name:'Exit cockpit'}).click();await page.clock.runFor(64)
 expect((await ship()).mode).toBe('grounded')
 await expect(page.locator('[data-entity][data-frame="planet:fixture"]').first()).toBeVisible()
 const built=await page.context().newPage()
 await boot(built,'','http://127.0.0.1:4175')
 await built.evaluate(value=>localStorage.setItem('salimon:expedition:v1',JSON.stringify(value)),saved)
 await built.reload()
 await expect.poll(async()=>{await built.clock.runFor(50);return built.locator('main').getAttribute('data-ship')}).not.toBeNull()
 await expect(built.locator('[data-entity][data-frame="planet:fixture"]')).toHaveCount(0)
 await expect(built.getByRole('button',{name:'begin-takeoff',exact:true})).toHaveCount(0)
 expect(JSON.parse((await built.locator('main').getAttribute('data-ship'))!).mode).toBe('flying')
 await expect.poll(async()=>{await built.clock.runFor(50);return built.locator('.top-down-scene').getAttribute('data-render-ready')}).toBe('true')
 await expect(built.locator('[data-entity="ship:scout"]')).toBeVisible()
 await expect(built.locator('[data-entity="person:player"]')).toBeVisible()
 await built.screenshot({path:info.outputPath('built-flight-interior.png')})
 await built.close()
 await info.attach('state.json' ,{body:JSON.stringify({backend,viewport:{width:1280,height:800},dpr:1,epoch:'2026-11-04T00:00:00Z',saved,landed:await ship()}),contentType:'application/json'})
})

test('FLIGHT-838 built save restores a rendered interior and usable inventory',async({page},info)=>{
 const {ResourceSession,RESOURCE_SAVE_KEY}=await import('../src/resourceSession.ts')
 const {requestInteraction,createTopDownState,PLAYER_ID}=await import('../src/topDownRuntime.ts')
 const {point2}=await import('../src/topDownFrames.ts')
 const {enterCockpit,leaveCockpit}=await import('../src/cockpit.ts')
 let raw:string|null=null,world=createTopDownState('interior',true)
 world={...world,entities:world.entities.map(e=>e.id===PLAYER_ID?{...e,anchor:{frame:'ship:scout',point:point2(0,4.7)}}:e)}
 world=requestInteraction(world,'scout:entry')
 world={...world,entities:world.entities.map(e=>e.id===PLAYER_ID?{...e,anchor:{frame:'ship:scout',point:point2(0,-3.1)}}:e)}
 world=enterCockpit({...world,selectedId:'scout:chair'})
 const session=new ResourceSession({getItem:()=>raw,setItem:(_,value)=>{raw=value}},world)
 expect(session.transfer({revision:0,from:{kind:'source',id:'source:landing:mineral:01'},to:{kind:'player'},resourceId:'mineral',grams:1000})).toBe(true)
 for(const kind of ['begin-takeoff','finish-takeoff'] as const)expect(session.transitionScout({kind},session.snapshot.revision,session.world.cockpit)).toBe(true)
 session.world=leaveCockpit(session.world);session.checkpoint()
 await page.addInitScript(({key,raw})=>localStorage.setItem(key,raw),{key:RESOURCE_SAVE_KEY,raw:raw!})
 await page.clock.install({time:new Date('2026-11-04T00:00:00Z')});await page.clock.pauseAt(new Date('2026-11-04T00:00:01Z'))
 await page.goto('http://127.0.0.1:4175/')
 await expect.poll(async()=>{await page.clock.runFor(50);return page.locator('.top-down-scene').getAttribute('data-render-ready')}).toBe('true')
 await expect(page.getByRole('img',{name:'Strict overhead Scout interior in flight'})).toBeVisible()
 await expect(page.locator('[data-entity="ship:scout"]')).toBeVisible();await expect(page.locator('[data-entity="person:player"]')).toBeVisible()
 await expect(page.locator('[data-entity][data-frame="planet:fixture"]')).toHaveCount(0)
 await page.getByRole('button',{name:/Field inventory/}).click()
 await expect(page.locator('#field-inventory')).toBeVisible();await expect(page.locator('[data-resource=mineral]')).toHaveText('1 kg')
 await page.screenshot({path:info.outputPath('built-restored-flight.png')})
 await info.attach('save.json',{body:raw!,contentType:'application/json'})
})
