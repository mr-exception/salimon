import { test, expect, type Page } from '@playwright/test'
import { boot, positionIn, scene, walkTo, walkTicks } from './worldJourney'
import { compareImages } from '../scripts/visual-comparison.ts'
async function objectClick(page: Page, id: string) {
  const point = await page.locator(`[data-entity="${id}"]`).evaluate(g => {
    const p = new DOMPoint().matrixTransform((g as SVGGraphicsElement).getScreenCTM()!)
    return { x: p.x, y: p.y }
  })
  await page.mouse.click(point.x, point.y, { button: 'right' }); await page.clock.runFor(32)
}
async function chooseAction(page: Page, label: string) {
  await page.getByRole('menuitem', { name: label }).click()
  await expect.poll(async () => { await page.clock.runFor(64); return page.locator('[data-command-status]').getAttribute('data-command-status') }, { timeout: 60000, intervals: [10, 25] }).toBe('completed')
}
async function groundClick(page: Page, x: number, y: number) {
  const point = await page.locator('[data-entity="ship:scout"]').evaluate((g, xy) => {
    const p = new DOMPoint(xy[0], xy[1]).matrixTransform((g as SVGGraphicsElement).getScreenCTM()!); return { x: p.x, y: p.y }
  }, [x, y])
  await page.mouse.click(point.x, point.y, { button: 'right' }); await page.clock.runFor(32)
}
const menu = (page: Page) => page.getByRole('menu')
test('MENU-892 built open/replace, no effects, keyboard accessibility, active clock and dismissal', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await boot(page, '', 'http://127.0.0.1:4175')
  const initial = await positionIn(page, 'ship:scout')
  await objectClick(page, 'scout:chair')
  await expect(menu(page)).toHaveAccessibleName('Actions for Cockpit chair')
  await expect(page.getByRole('menuitem', { name: 'Inspect', exact: true })).toBeFocused()
  const cockpit = page.getByRole('menuitem', { name: 'Use cockpit' })
  await expect(cockpit).toHaveAttribute('aria-disabled', 'false')
  await expect(cockpit).toContainText('Approach, then use cockpit')
  const tick = Number(await page.locator('main').getAttribute('data-tick'))
  await page.clock.runFor(1000)
  expect(Number(await page.locator('main').getAttribute('data-tick'))).toBeGreaterThan(tick)
  expect(await positionIn(page, 'ship:scout')).toEqual(initial)
  await expect(page.locator('.panoramic')).toHaveCount(0)
  await page.keyboard.press('End'); await expect(cockpit).toBeFocused()
  await page.keyboard.press('ArrowDown'); await expect(page.getByRole('menuitem', { name: 'Inspect', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowUp'); await expect(cockpit).toBeFocused(); await page.keyboard.press('Home')
  await page.screenshot({ path: info.outputPath('remote-approach-menu.png') })
  await page.keyboard.press('Enter'); await expect.poll(async () => { await page.clock.runFor(64); return page.locator('[data-command-status]').getAttribute('data-command-status') }, { intervals: [10, 25] }).toBe('completed'); await expect(menu(page)).toHaveCount(0); await expect(scene(page)).toBeFocused()
  await expect(page.locator('.top-down-interaction')).toContainText('Cockpit chair. Physical actions require proximity.')
  expect(await positionIn(page, 'ship:scout')).toEqual(initial)
  await objectClick(page, 'scout:chair'); await objectClick(page, 'scout:fabricator')
  await expect(menu(page)).toHaveAccessibleName('Actions for Fabricator'); await expect(menu(page)).toHaveCount(1)
  await page.keyboard.press('Escape'); await expect(menu(page)).toHaveCount(0); await expect(scene(page)).toBeFocused()
  await objectClick(page, 'scout:fabricator'); await page.keyboard.press('Tab'); await expect(menu(page)).toHaveCount(0)
  await objectClick(page, 'scout:fabricator'); await page.mouse.click(850, 500); await expect(menu(page)).toHaveCount(0)
  expect(await positionIn(page, 'ship:scout')).toEqual(initial)
  await objectClick(page, 'scout:chair'); await groundClick(page, -4, 7)
  await expect(menu(page)).toHaveCount(0)
  await expect(page.locator('[data-movement-status]')).toHaveAttribute('data-movement-status', 'moving')
  await page.keyboard.press('Escape')
  await objectClick(page, 'scout:chair'); await page.getByRole('button', { name: /Field inventory/ }).focus()
  await expect(menu(page)).toHaveCount(0)
  await objectClick(page, 'scout:chair'); await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  await expect(menu(page)).toHaveCount(0)
  expect(errors).toEqual([])
  await info.attach('menu-state.json', { body: JSON.stringify({ initial, final: await positionIn(page, 'ship:scout'), tick, errors, input: 'actual Playwright mouse/keyboard; dispatched window blur', route: 'built /', renderer: 'SVG CPU' }), contentType: 'application/json' })
})
test('MENU-892 built transformed edge clamp, repeated pixels and HUD isolation', async ({ page }, info) => {
  await boot(page, '', 'http://127.0.0.1:4175')
  await page.setViewportSize({ width: 960, height: 720 }); await page.clock.runFor(64)
  await page.mouse.move(600, 400); await page.mouse.wheel(0, -300)
  await expect.poll(async () => { await page.clock.runFor(32); return Number(await scene(page).getAttribute('data-camera-scale')) }).toBeGreaterThan(26)
  const start = await positionIn(page, 'ship:scout')
  const at = await page.locator('[data-entity="scout:chair"]').evaluate(g => {
    const p = new DOMPoint().matrixTransform((g as SVGGraphicsElement).getScreenCTM()!); return { x: p.x, y: p.y }
  })
  await page.mouse.move(480, 360); await page.mouse.down({ button: 'middle' })
  await page.mouse.move(480 + 915 - at.x, 360 + 660 - at.y, { steps: 4 }); await page.mouse.up({ button: 'middle' }); await page.clock.runFor(32)
  await objectClick(page, 'scout:chair')
  const box = (await menu(page).boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(8); expect(box.y).toBeGreaterThanOrEqual(8)
  expect(box.x + box.width).toBeLessThanOrEqual(952); expect(box.y + box.height).toBeLessThanOrEqual(712)
  const scale = await scene(page).getAttribute('data-camera-scale')
  await menu(page).hover(); await page.mouse.wheel(0, 300); await page.clock.runFor(64)
  expect(await scene(page).getAttribute('data-camera-scale')).toBe(scale)
  // Restore the keyboard-focused row after hover before deterministic capture.
  await page.keyboard.press('Home')
  const original = await page.screenshot({ path: info.outputPath('edge-menu.png') })
  await page.keyboard.press('Escape')
  const closed = await page.screenshot({ path: info.outputPath('edge-closed.png') })
  expect(compareImages(original, closed).pass).toBe(false)
  await objectClick(page, 'scout:chair')
  const repeat = await page.screenshot({ path: info.outputPath('edge-repeat.png') })
  const diff = compareImages(original, repeat); expect(diff.pass).toBe(true)
  await info.attach('repeat-diff.png', { body: diff.diff, contentType: 'image/png' })
  await info.attach('edge-state.json', { body: JSON.stringify({ box, scale, changedPixels: diff.changedPixels, repeat: diff.pass, negative: true }), contentType: 'application/json' })
  expect(await positionIn(page, 'ship:scout')).toEqual(start)
})
test('MENU-892 built container confirmation, door and cockpit dispatch retain E fallback', async ({ page }, info) => {
  await boot(page, '', 'http://127.0.0.1:4175')
  await groundClick(page, 0, 4.4)
  await expect.poll(async () => { await page.clock.runFor(250); const status = await page.locator('[data-movement-status]').getAttribute('data-movement-status'); expect(status).not.toBe('failed'); return status }, { timeout: 60000, intervals: [10, 25] }).toBe('arrived')
  await objectClick(page, 'scout:entry')
  await expect(page.getByRole('menuitem', { name: 'Close door' })).toHaveAttribute('aria-disabled', 'false')
  await chooseAction(page, 'Close door')
  await expect(page.locator('[data-entity="scout:entry"]')).toHaveAttribute('data-door-state', 'closed')
  await page.keyboard.press('e'); await page.clock.runFor(32)
  await expect(page.locator('[data-entity="scout:entry"]')).toHaveAttribute('data-door-state', 'open')
  await walkTo(page, [.6, 4.25], 'ship:scout', true)
  const saved = await page.evaluate(() => localStorage.getItem('salimon:expedition:v1'))
  await objectClick(page, 'scout:storage')
  await chooseAction(page, 'Use Resource Container')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.screenshot({ path: info.outputPath('container-panel.png') })
  const inventory = (raw: string | null) => JSON.parse(raw!).inventory
  expect(inventory(await page.evaluate(() => localStorage.getItem('salimon:expedition:v1')))).toEqual(inventory(saved))
  await page.keyboard.press('Escape'); await page.clock.runFor(32)
  await groundClick(page, 0, -3.0)
  await expect.poll(async () => { await page.clock.runFor(250); const status = await page.locator('[data-movement-status]').getAttribute('data-movement-status'); expect(status).not.toBe('failed'); return status }, { timeout: 60000, intervals: [10, 25] }).toBe('arrived')
  await objectClick(page, 'scout:chair')
  await chooseAction(page, 'Use cockpit')
  await expect(page.locator('.panoramic')).toBeVisible(); await expect(menu(page)).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('cockpit-result.png') })
})

test('MENU-892 built mining requires equipment and explicit selection; remote Inspect earns no discovery', async ({ page }, info) => {
  await boot(page, '', 'http://127.0.0.1:4175')
  const source = 'source:landing:mineral:01'
  const before = await page.evaluate(() => localStorage.getItem('salimon:expedition:v1'))
  await objectClick(page, source)
  await page.getByRole('menuitem', { name: 'Inspect', exact: true }).click()
  expect(await page.evaluate(() => localStorage.getItem('salimon:expedition:v1'))).toBe(before)
  await walkTicks(page, 'w', 75); await walkTicks(page, 'a', 25)
  await objectClick(page, source)
  await expect(page.getByRole('menuitem', { name: 'Gather / Mine' })).toHaveAccessibleDescription(/tool/)
  await page.getByRole('menuitem', { name: 'Gather / Mine' }).press('Enter')
  await expect(menu(page)).toBeVisible()
  await expect(page.getByLabel('Resource inventory')).toHaveAttribute('data-gathering', '')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Equip gathering tool' }).click()
  await objectClick(page, source)
  await expect(page.getByRole('menuitem', { name: 'Gather / Mine' })).toHaveAttribute('aria-disabled', 'false')
  await expect(page.getByLabel('Resource inventory')).toHaveAttribute('data-gathering', '')
  await chooseAction(page, 'Gather / Mine')
  await walkTicks(page, [], 60)
  await expect(page.locator('[data-inventory-weight]')).toHaveText('1 / 10 kg')
  await page.screenshot({ path: info.outputPath('menu-mining-result.png') })
  await page.keyboard.press('Escape')
  await info.attach('mining-save.json', { body: (await page.evaluate(() => localStorage.getItem('salimon:expedition:v1')))!, contentType: 'application/json' })
})
