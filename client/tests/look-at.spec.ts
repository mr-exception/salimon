import { test, expect, type Page } from '@playwright/test'
type State = { ship: { yaw: number; pitch: number; velocityMps: number[]; throttle: number; alignment: unknown; mode: string }; view: { quaternion: number[]; fov: number }; lookingAt: boolean; selected: string | null; contacts: { id: string; name: string }[]; markers: { ids: string[] }[]; renderer: string }
const state = (page: Page) => page.evaluate(() => (window as unknown as { lookSnapshot(): State }).lookSnapshot())
async function boot(page: Page, grounded = false) {
 await page.goto(`/tests/look-at.html${grounded ? '?grounded' : ''}`)
 await expect.poll(async () => (await state(page))?.renderer).toContain('SwiftShader')
}
async function choose(page: Page, name: string) {
 await page.getByRole('textbox').fill(name)
 await page.getByRole('button', { name, exact: true }).click()
}
test('LOOK-1 rear browser contact, opaque foreground, independent ship alignment and cancellation', async ({ page }, info) => {
 const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
 await boot(page)
 await expect(page.getByRole('button', { name: 'Look at', exact: true })).toHaveCount(0)
 await page.getByRole('button', { name: 'Pulse', exact: true }).click()
 const initial = await state(page)
 expect(initial.markers).toHaveLength(0)
 await choose(page, 'Behind')
 await page.getByRole('button', { name: 'Zoom', exact: true }).click()
 // The observer publishes after the render frame, not synchronously with clicks.
 await expect.poll(async () => (await state(page)).view.fov).toBeLessThan(initial.view.fov)
 const start = await state(page)
 await page.getByRole('button', { name: 'Look at', exact: true }).click()
 await expect.poll(async () => (await state(page)).view.quaternion).not.toEqual(start.view.quaternion)
 await expect.poll(async () => (await state(page)).lookingAt).toBe(false)
 const looked = await state(page)
 expect(looked.ship).toEqual(initial.ship)
 expect(looked.view.fov).toBe(start.view.fov)
 expect(Math.abs(looked.view.quaternion[1])).toBeCloseTo(1, 8)
 expect(looked.markers.flatMap(m => m.ids)).not.toContain('Behind')
 await page.locator('canvas').click({ position: { x: 30, y: 500 } })
 const opaque = await page.locator('canvas').screenshot()
 await page.getByRole('button', { name: 'Toggle hidden optical control', exact: true }).click()
 await page.locator('canvas').click({ position: { x: 30, y: 500 } })
 expect((await page.locator('canvas').screenshot()).equals(opaque)).toBe(true)
 await info.attach('occluded.png', { body: opaque, contentType: 'image/png' })
 await page.getByRole('button', { name: 'Set direction', exact: true }).click()
 await expect.poll(async () => (await state(page)).ship.yaw).not.toBe(initial.ship.yaw)
 const turned = await state(page)
 expect(turned.view).toEqual(looked.view)
 expect(turned.ship.velocityMps).toEqual(initial.ship.velocityMps)
 // Camera input does not cancel ongoing physical alignment.
 await page.locator('canvas').click({ position: { x: 30, y: 500 } })
 await page.keyboard.press('KeyD')
 expect((await state(page)).ship.alignment).not.toBeNull()
 await page.keyboard.press('ArrowLeft')
 await expect.poll(async () => (await state(page)).ship.alignment).toBeNull()
 // Help disclosure is a keyboard control, never a steering surface.
 await page.locator('summary').focus()
 const helpFocus = await state(page)
 await page.keyboard.press('KeyD'); await page.keyboard.press('ArrowLeft')
 expect((await state(page)).view).toEqual(helpFocus.view)
 expect((await state(page)).ship.yaw).toBe(helpFocus.ship.yaw)
 // Focused typing cannot move either controller.
 await page.getByRole('textbox').focus()
 const focused = await state(page)
 await page.keyboard.press('KeyD'); await page.keyboard.press('ArrowLeft')
 expect((await state(page)).view).toEqual(focused.view)
 expect((await state(page)).ship.yaw).toEqual(focused.ship.yaw)
 expect((await state(page)).ship.pitch).toEqual(focused.ship.pitch)
 expect((await state(page)).ship.velocityMps).toEqual(focused.ship.velocityMps)
 await page.getByRole('button', { name: 'Reset view', exact: true }).click()
 await page.getByRole('button', { name: 'Look at', exact: true }).click()
 await expect.poll(async () => (await state(page)).lookingAt).toBe(true)
 await page.locator('canvas').click({ position: { x: 30, y: 500 } })
 await expect.poll(async () => (await state(page)).lookingAt).toBe(false)
 const cancelled = await state(page)
 await page.getByRole('textbox').focus()
 expect((await state(page)).view).toEqual(cancelled.view)
 // Loss during a captured animation clears commands without retaining a ghost.
 await page.getByRole('button', { name: 'Look at', exact: true }).click()
 await page.getByRole('button', { name: 'Leave range', exact: true }).click()
 await expect(page.getByRole('status')).toHaveText('No selection')
 await expect(page.getByRole('button', { name: 'Look at', exact: true })).toHaveCount(0)
 await expect(page.getByRole('button', { name: 'Set direction', exact: true })).toHaveCount(0)
 await expect.poll(async () => (await state(page)).lookingAt).toBe(false)
 const lost = await state(page)
 expect(Math.abs(lost.view.quaternion[1])).toBeCloseTo(1, 8)
 expect(lost.contacts).toEqual([]); expect(lost.selected).toBeNull()
 expect(errors).toEqual([])
 await info.attach('measurements.json', { body: JSON.stringify({ initial, start, looked, turned, focused, cancelled, lost, opaqueControl: 'byte-identical', errors }, (_, v) => typeof v === 'bigint' ? String(v) : v, 2), contentType: 'application/json' })
})
test('LOOK-2 shared grounded Scout observes other bodies, Vesper actions remain disabled', async ({ page }, info) => {
 await boot(page, true)
 await page.getByRole('button', { name: 'Pulse', exact: true }).click()
 const initial = await state(page)
 const planet = initial.contacts.find(b => b.id === 'vesper')!
 await choose(page, planet.name)
 await expect(page.getByText(`Current landing planet: ${planet.name}`)).toBeVisible()
 await expect(page.getByRole('button', { name: 'Look at', exact: true })).toBeDisabled()
 await expect(page.getByRole('button', { name: 'Set direction', exact: true })).toBeDisabled()
 await info.attach('vesper.png', { body: await page.screenshot(), contentType: 'image/png' })
 const other = initial.contacts.find(b => b.id !== 'vesper')!
 await choose(page, other.name)
 await expect(page.getByRole('button', { name: 'Look at', exact: true })).toBeEnabled()
 await expect(page.getByRole('button', { name: 'Set direction', exact: true })).toBeDisabled()
 await page.getByRole('button', { name: 'Look at', exact: true }).click()
 await expect.poll(async () => (await state(page)).view.quaternion).not.toEqual(initial.view.quaternion)
 await expect.poll(async () => (await state(page)).lookingAt).toBe(false)
 const observed = await state(page)
 expect(observed.ship).toEqual(initial.ship)
 await info.attach('grounded-observation.png', { body: await page.screenshot(), contentType: 'image/png' })
 await info.attach('measurements.json', { body: JSON.stringify({ initial, observed }, (_, v) => typeof v === 'bigint' ? String(v) : v, 2), contentType: 'application/json' })
})
