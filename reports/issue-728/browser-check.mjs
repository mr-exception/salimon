import assert from 'node:assert/strict'
import fs from 'node:fs'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE_URL || 'playwright')
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']})
const page=await browser.newPage({viewport:{width:1280,height:800}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
await page.goto('http://localhost:5173');await page.waitForTimeout(800)
assert.equal(await page.locator('.edge').count(),0)
await page.waitForFunction(()=>document.querySelector('.legend')?.textContent.includes('pulse #1'),{timeout:15000})
await page.mouse.move(400,300)
for(let i=0;i<30;i++){await page.mouse.wheel(0,-120);await page.waitForTimeout(20)}
await page.waitForTimeout(600)
await page.getByRole('button',{name:'◇ Caligo',exact:true}).waitFor({timeout:5000})
await page.getByRole('button',{name:'◇ Caligo',exact:true}).click()
await page.getByRole('button',{name:'Set direction',exact:true}).waitFor()
assert.match(await page.locator('aside').innerText(),/Caligo/)
const before=await page.locator('.stat').allTextContents()
await page.mouse.move(400,300);await page.mouse.wheel(0,-300);await page.waitForTimeout(1000)
assert.deepEqual(await page.locator('.stat').allTextContents(),before)
const labels=await page.locator('.edge').allTextContents();assert.ok(labels.length>1)
assert.deepEqual(errors,[])
await page.screenshot({path:'reports/issue-728/scanner.png'})
const gpu=await page.locator('canvas').evaluate(c=>{const gl=c.getContext('webgl2');return gl.getParameter(gl.getExtension('WEBGL_debug_renderer_info').UNMASKED_RENDERER_WEBGL)})
fs.writeFileSync('reports/issue-728/browser.json',JSON.stringify({viewport:[1280,800],gpu,noRevealBeforePulse:true,edgeSelects:'Caligo',zoomPreservesShip:true,labels,errors},null,2)+'\n')
await browser.close()
