test('SLICE-880 competing tab cannot advance or claim the active job', async ({ page, context }, info) => {
  await seed(page, fixture('powered')); await boot(page, '', origin)
  // Playwright's clock is context-wide. Freeze the authorized writer so advancing
  // the competing page's clock isolates whether that tab can mutate the job.
  await page.getByRole('button', { name: 'Pause [P]', exact: true }).click()
  const before = await saved(page)
  const other = await context.newPage()
  try {
    await boot(other, '', origin)
    await expect(other.getByLabel('Resource inventory')).toContainText('Another tab')
    await expect(other.getByRole('button', { name: 'Equip gathering tool' })).toBeDisabled()
    await other.keyboard.press('e'); await other.clock.runFor(21000)
    expect(await saved(page)).toEqual(before)
    await expect(panel(other)).toHaveCount(0)
    await other.screenshot({ path: info.outputPath('competing-tab.png') })
  } finally { await other.close() }
  await page.getByRole('button', { name: 'Resume [P]', exact: true }).click()
  await page.clock.runFor(21000)
  const after = await saved(page)
  expect(after.fabricator.completed).toBe(1); expect(after.fabricator.claimed).toBe(0)
  expect(after.fabricator.tray.count).toBe(1)
  expect(after.core.spentJ60).toBe(100000 * 60)
  await info.attach('single-writer.json', { body: JSON.stringify({ before, after }, null, 2), contentType: 'application/json' })
})

