async function reloadWorld(page: Page) {
  await page.reload()
  await expect.poll(async () => { await page.clock.runFor(50); return page.locator('[data-render-ready]').getAttribute('data-render-ready') }).toBe('true')
  await expect(page.getByRole('button', { name: 'Equip gathering tool' })).toBeEnabled()
  await page.clock.runFor(50)
}

