import { test, expect } from '@playwright/test'
import { compareImages, POLICY } from '../scripts/visual-comparison.ts'
import { RESOURCE_SAVE_KEY } from '../src/resourceSession.ts'
import { boot, position, walkTicks, walkTo } from './worldJourney'

test('GATHER-1 built mixed gathering, interruption, atomic reload and weight feedback repeat', async ({ browser }, info) => {
  const originals: Record<string, Buffer> = {}, records = []
  for (let replay = 0; replay < 2; replay++) {
    const context = await browser.newContext({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1, locale: 'en-US', timezoneId: 'UTC', colorScheme: 'dark', reducedMotion: 'reduce' })
    const page = await context.newPage(), errors: string[] = []
    page.on('pageerror', e => errors.push(e.message))
    try {
      await boot(page, '', 'http://127.0.0.1:4175')
      await expect(page.locator('[data-inventory-weight]')).toHaveText('0 / 10 kg')
      const capture = async (name: string) => {
        await page.clock.runFor(5000)
        const png = await page.screenshot({ path: info.outputPath(`${name}-${replay}.png`), fullPage: true })
        if (replay === 0) originals[name] = png
        else {
          const result = compareImages(originals[name]!, png)
          await info.attach(`${name}-repeat.json`, { body: JSON.stringify({ pass: result.pass, changedPixels: result.changedPixels, rawChangedPixels: result.rawChangedPixels, policy: POLICY }), contentType: 'application/json' })
          await info.attach(`${name}-diff.png`, { body: result.diff, contentType: 'image/png' })
          expect(result.pass, name).toBe(true)
        }
      }
      await walkTicks(page, 'w', 75); await walkTicks(page, 'a', 25)
      await page.getByRole('button', { name: 'Equip gathering tool' }).click()
      await capture('gather-source-ready')
      await page.keyboard.press('e')
      await expect(page.getByLabel('Resource inventory')).toHaveAttribute('data-gathering', 'source:landing:mineral:01')
      await walkTicks(page, [], 59)
      await expect(page.locator('[data-resource="mineral"]')).toHaveText('0 L')
      await walkTicks(page, [], 1)
      await expect(page.locator('[data-resource="mineral"]')).toHaveText('1 L')
      await expect(page.locator('[data-inventory-weight]')).toHaveText('2.5 / 10 kg')
      await walkTicks(page, [], 120)
      await expect(page.locator('[data-resource="mineral"]')).toHaveText('3 L')
      await walkTicks(page, [], 59)
      await page.keyboard.press('Escape')
      const beforeReload = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), RESOURCE_SAVE_KEY)
      const oldPosition = await position(page)
      await page.reload()
      await expect(page.locator('[data-resource="mineral"]')).toHaveText('3 L')
      await expect(page.getByLabel('Resource inventory')).toHaveAttribute('data-gathering', '')
      expect(await position(page)).toEqual(oldPosition)
      const afterReload = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), RESOURCE_SAVE_KEY)
      expect(afterReload).toEqual(beforeReload)
      expect(afterReload.sources['source:landing:mineral:01'].remainingLitres).toBe(21)
      await expect(page.getByRole('button', { name: 'Equip gathering tool' })).toBeVisible()
      await page.getByRole('button', { name: 'Equip gathering tool' }).click()
      await walkTo(page, [-6, 4.5], 'planet:fixture', true)
      await walkTo(page, [-5, 4.5], 'planet:fixture', true)
      await page.keyboard.press('e'); await walkTicks(page, [], 300)
      await expect(page.locator('[data-resource="biomass"]')).toHaveText('5 L')
      await expect(page.locator('[data-inventory-weight]')).toHaveText('10 / 10 kg')
      await expect(page.locator('[data-inventory-volume]')).toHaveText('8 / 10 L')
      await expect(page.getByRole('status')).toContainText('weight limit')
      for (let i = 0; i < 6; i++) await page.keyboard.press('e')
      await walkTicks(page, [], 120)
      await expect(page.locator('[data-resource="biomass"]')).toHaveText('5 L')
      await expect(page.locator('[data-entity="source:landing:biology:01"]')).toHaveAttribute('data-remaining-litres', '25')
      await capture('gather-weight-full')
      const snapshot = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), RESOURCE_SAVE_KEY)
      expect(snapshot.inventory.quantities).toEqual({ mineral: 3, biomass: 5 })
      expect(errors).toEqual([])
      records.push({ replay, snapshot, beforeReload, afterReload, errors, browser: browser.version(), input: 'actual keyboard/mouse, built production entry; storage and DOM observations only' })
    } finally { await context.close() }
  }
  const negative = compareImages(originals['gather-source-ready']!, originals['gather-weight-full']!)
  expect(negative.pass).toBe(false)
  await info.attach('gathering-records.json', { body: JSON.stringify({ records, negative: { pass: negative.pass, changedPixels: negative.changedPixels }, policy: POLICY, baseline: 'review candidates; no approved navigation baseline changed' }, null, 2), contentType: 'application/json' })
})

test('GATHER-2 biological volume cap, movement interruption and competing browser tab', async ({ page, context }, info) => {
  await boot(page, '', 'http://127.0.0.1:4175')
  await expect(page.locator('[data-inventory-weight]')).toBeVisible()
  await walkTo(page, [-5, 4.5], 'planet:fixture', true)
  await page.getByRole('button', { name: 'Equip gathering tool' }).click()
  await page.keyboard.press('e'); await walkTicks(page, [], 59)
  await walkTicks(page, 'a', 1)
  await expect(page.getByLabel('Resource inventory')).toHaveAttribute('data-gathering', '')
  await expect(page.locator('[data-resource="biomass"]')).toHaveText('0 L')
  await page.keyboard.press('e'); await walkTicks(page, [], 600)
  await expect(page.locator('[data-resource="biomass"]')).toHaveText('10 L')
  await expect(page.locator('[data-inventory-weight]')).toHaveText('5 / 10 kg')
  await expect(page.locator('[data-inventory-volume]')).toHaveText('10 / 10 L')
  await expect(page.getByRole('status')).toContainText('volume limit')
  const other = await context.newPage()
  await boot(other, '', 'http://127.0.0.1:4175')
  await expect(other.getByLabel('Resource inventory')).toContainText('Another tab')
  await expect(other.getByRole('button', { name: 'Equip gathering tool' })).toBeDisabled()
  const raw = await page.evaluate(key => localStorage.getItem(key), RESOURCE_SAVE_KEY)
  await other.close()
  await page.clock.runFor(5000)
  await page.screenshot({ path: info.outputPath('gather-volume-full.png'), fullPage: true })
  await page.reload()
  await expect(page.locator('[data-resource="biomass"]')).toHaveText('10 L')
  expect(await page.evaluate(key => localStorage.getItem(key), RESOURCE_SAVE_KEY)).toBe(raw)
  await info.attach('volume-save.json', { body: raw!, contentType: 'application/json' })
})
