import { test, expect } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'

test('shared components retain semantics, keyboard isolation and modal focus', async ({ page }) => {
  await page.goto('/tests/ui.html')
  const planet = page.getByRole('main', { name: 'planet context' })
  await expect(planet.getByRole('meter', { name: 'Health' })).toHaveAttribute('aria-valuetext', '160 / 200 HP')
  await expect(planet.getByRole('progressbar', { name: 'Scan' })).toHaveAttribute('value', '3')
  await expect(planet.getByRole('button', { name: 'Inspect settings' })).toBeVisible()
  const blocked = planet.getByRole('button', { name: 'Take off' })
  await blocked.focus()
  await expect(blocked).toHaveAccessibleDescription('Grounded: takeoff unavailable')
  await page.keyboard.press('Enter')
  await planet.getByRole('button', { name: 'Saving' }).click({ force: true })
  await expect(planet.locator('output')).toHaveText('0')
  await planet.getByRole('textbox', { name: 'Instrument label' }).fill('W input')
  await page.keyboard.press('w')
  await expect.poll(() => page.evaluate(() => (window as unknown as {shortcutCount:number}).shortcutCount)).toBe(0)
  const opener = planet.getByRole('button', { name: 'Inspect equipment' })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: 'Equipment review' })
  await expect(dialog).toBeFocused()
  await page.keyboard.press('w')
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'Close Equipment review' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('textbox')).toBeFocused()
  await page.keyboard.press('w')
  await expect.poll(() => page.evaluate(() => (window as unknown as {shortcutCount:number}).shortcutCount)).toBe(0)
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(opener).toBeFocused()
  await opener.click()
  await dialog.getByRole('button', { name: 'Close Equipment review' }).click()
  await expect(opener).toBeFocused()
})

for (const width of [960, 1280, 1920]) test(`repeatable light/dark state references at ${width}`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width, height: width === 960 ? 600 : width === 1280 ? 720 : 1080 })
  await page.goto('/tests/ui.html')
  await page.evaluate(() => document.fonts.ready)
  const directory = '../reports/issue-826/captures'
  await mkdir(directory, { recursive: true })
  const hashes: Record<string, string> = {}
  for (const context of ['planet', 'space']) {
    const region = page.getByRole('main', { name: `${context} context` })
    const primary = region.getByRole('button', { name: 'Inspect equipment' })
    await primary.hover()
    const hover = await primary.evaluate(el => getComputedStyle(el).backgroundColor)
    expect(hover).toBe('rgb(9, 20, 28)')
    await page.keyboard.press('Tab')
    await primary.focus()
    expect(await primary.evaluate(el => getComputedStyle(el).outlineWidth)).toBe('2px')
    expect(await primary.evaluate(el => getComputedStyle(el).transitionDuration)).toBe('0s, 0s')
    if (width === 960 && context === 'planet') {
      const original = await primary.screenshot()
      await primary.evaluate(el => { el.style.backgroundColor = '#ff0000' })
      expect((await primary.screenshot()).equals(original)).toBe(false)
      await primary.evaluate(el => { el.style.backgroundColor = '' })
    }
    const first = await region.screenshot({ animations: 'disabled' })
    const repeat = await region.screenshot({ animations: 'disabled' })
    expect(repeat.equals(first)).toBe(true)
    const path = `${directory}/${context}-${width}.png`
    await writeFile(path, first)
    hashes[path] = createHash('sha256').update(first).digest('hex')
    await testInfo.attach(`${context}-${width}`, { body: first, contentType: 'image/png' })
    await primary.click()
    const dialog = page.getByRole('dialog', { name: 'Equipment review' })
    const box = await dialog.boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.y).toBeGreaterThanOrEqual(0)
    const dialogImage = await dialog.screenshot()
    expect((await dialog.screenshot()).equals(dialogImage)).toBe(true)
    await writeFile(`${directory}/dialog-${context}-${width}.png`, dialogImage)
    hashes[`${directory}/dialog-${context}-${width}.png`] = createHash('sha256').update(dialogImage).digest('hex')
    await page.keyboard.press('Escape')
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await writeFile(`${directory}/hashes-${width}.json`, JSON.stringify(hashes, null, 2) + '\n')
})
