for (const failure of ['write', 'stale'] as const) test(`SLICE-880 ${failure} claim preserves tray and durable bytes`, async ({ page }, info) => {
  await seed(page, fixture('complete')); await boot(page, '', origin)
  await page.keyboard.press('e'); await expect(panel(page)).toBeVisible()
  if (failure === 'write') await page.evaluate(key => {
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function(k, v) { if (k === key) throw new DOMException('Injected quota failure', 'QuotaExceededError'); original.call(this, k, v) }
  }, RESOURCE_SAVE_KEY)
  else await page.evaluate(key => localStorage.setItem(key, localStorage.getItem(key)! + ' '), RESOURCE_SAVE_KEY)
  const bytes = await page.evaluate(key => localStorage.getItem(key), RESOURCE_SAVE_KEY)
  await page.getByRole('button', { name: 'Claim output' }).click()
  await expect(page.getByRole('status', { name: 'Container feedback' })).toContainText('Saving failed')
  expect(await page.evaluate(key => localStorage.getItem(key), RESOURCE_SAVE_KEY)).toBe(bytes)
  await expect(page.getByRole('button', { name: 'Claim output' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('rejected-claim.png') })
  await reloadWorld(page); await page.getByRole('button', { name: 'Use Fabricator', exact: true }).click()
  await page.getByRole('button', { name: 'Claim output' }).click()
  const recovered = await saved(page)
  expect(recovered.fabricator.claimed).toBe(1)
  expect(recovered.fabricator.tray).toBeNull()
  expect(recovered.inventory.items[MARKER_KIT_ID]).toBe(1)
  await info.attach('failure-recovery.json', { body: JSON.stringify({ failure, before: JSON.parse(bytes!), recovered }, null, 2), contentType: 'application/json' })
})

