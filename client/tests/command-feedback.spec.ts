import { test, expect, type Page } from '@playwright/test'
import { boot, positionIn, scene, walkTicks } from './worldJourney'
import { compareImages } from '../scripts/visual-comparison.ts'

test.use({ trace: { mode: 'on', screenshots: true, snapshots: false, sources: true } })

const source = 'source:landing:mineral:01'
const receipt = (page: Page) => page.locator('[data-command-status]')
async function point(page: Page, id: string, x = 0, y = 0) {
  return page.locator(`[data-entity="${id}"]`).evaluate((g, p) => {
    const v = new DOMPoint(...p).matrixTransform((g as SVGGraphicsElement).getScreenCTM()!)
    return { x: v.x, y: v.y }
  }, [x, y])
}
async function choose(page: Page, id: string, action: string) {
  const p = await point(page, id)
  await page.mouse.click(p.x, p.y, { button: 'right' })
  await page.getByRole('menuitem', { name: action }).click()
  await page.clock.runFor(64)
}
async function finish(page: Page) {
  await expect.poll(async () => {
    await page.clock.runFor(250)
    const status = await receipt(page).getAttribute('data-command-status')
    expect(status).not.toBe('failed'); expect(status).not.toBe('cancelled')
    return status
  }, { timeout: 60000, intervals: [10, 25] }).toBe('completed')
}
const saved = (page: Page) => page.evaluate(() => JSON.parse(localStorage.getItem('salimon:expedition:v1')!))

test('UX-894 built mouse-only obstruction → mine → confirmed deposit → cockpit and durable reload', async ({ page }, info) => {
  await boot(page, '', 'http://127.0.0.1:4175')
  // Reach an outdoor point around the hull before choosing a remote mineral.
  const target = await point(page, 'ship:scout', -4, 4)
  await page.mouse.click(target.x, target.y, { button: 'right' })
  await expect(page.locator('.command-feedback')).toContainText('Moving to destination')
  await expect(page.getByRole('button', { name: 'Cancel command' })).toBeVisible()
  await expect.poll(async () => { await page.clock.runFor(250); return page.locator('[data-movement-status]').getAttribute('data-movement-status') }, { timeout: 60000, intervals: [10, 25] }).toBe('arrived')
  await expect(page.locator('[data-entity="person:player"]')).toHaveAttribute('data-frame', 'planet:fixture')
  await page.getByRole('button', { name: 'Equip gathering tool' }).click()
  await choose(page, source, 'Gather / Mine')
  await expect(receipt(page)).toContainText('Moving to')
  await page.screenshot({ path: info.outputPath('moving-to-mineral.png') })
  await finish(page)
  await expect(receipt(page)).toContainText('Mining')
  await walkTicks(page, [], 60)
  await expect(page.locator('[data-inventory-weight]')).toHaveText('1 / 10 kg')
  const original = await page.screenshot({ path: info.outputPath('mining.png') })
  const repeat = await page.screenshot({ path: info.outputPath('mining-repeat.png') })
  const comparison = compareImages(original, repeat)
  expect(comparison.pass).toBe(true)
  await info.attach('repeat-diff.png', { body: comparison.diff, contentType: 'image/png' })
  await choose(page, 'scout:storage', 'Use Resource Container'); await finish(page)
  const panel = page.getByRole('dialog', { name: 'Resource Container', exact: true })
  const before = await saved(page)
  await panel.getByRole('textbox', { name: 'Amount in grams' }).fill('333')
  await panel.getByRole('button', { name: 'Review deposit' }).click()
  expect((await saved(page)).inventory).toEqual(before.inventory)
  await panel.getByRole('button', { name: 'Confirm deposit' }).click()
  const committed = await saved(page)
  expect(committed.inventory.quantities.mineral).toBe(667)
  expect(committed.stores['scout:storage'].quantities.mineral).toBe(333)
  await panel.getByRole('button', { name: /Close/ }).click()
  await choose(page, 'scout:chair', 'Use cockpit'); await finish(page)
  await expect(page.locator('.panoramic')).toBeVisible()
  const backend = await page.locator('.panoramic canvas').evaluate(canvas => {
    const gl = (canvas as HTMLCanvasElement).getContext('webgl2')!
    const debug = gl.getExtension('WEBGL_debug_renderer_info')
    return { version: gl.getParameter(gl.VERSION), renderer: gl.getParameter(debug?.UNMASKED_RENDERER_WEBGL ?? gl.RENDERER) }
  })
  expect(backend.renderer).toBeTruthy()
  await page.screenshot({ path: info.outputPath('cockpit.png') })
  await page.reload(); await page.clock.runFor(200)
  await expect.poll(async () => { await page.clock.runFor(50); return saved(page) }).toMatchObject({ inventory: { quantities: { mineral: 667 } }, stores: { 'scout:storage': { quantities: { mineral: 333 } } } })
  expect(JSON.stringify(await saved(page))).not.toMatch(/objectCommand|groundCommand|waypoints/)
  await expect(receipt(page)).toHaveCount(0)
  await info.attach('journey-state.json', { body: JSON.stringify({ before, committed, reloaded: await saved(page), repeat: { pass: comparison.pass, changedPixels: comparison.changedPixels }, input: 'Playwright desktop mouse; keyboard only for amount entry', backend: { world: 'SVG CPU', cockpit: backend }, viewport: '1280x800 DPR1' }), contentType: 'application/json' })
})

test('UX-894 built Help, overlays, Cancel, hidden-tab interruption and keyboard fallback', async ({ page }, info) => {
  await boot(page, '', 'http://127.0.0.1:4175')
  const start = await positionIn(page, 'ship:scout')
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  const help = page.getByRole('dialog', { name: 'Surface controls' })
  await expect(help).toContainText('Right-click an object: always open')
  await expect(help).toContainText('topmost menu or dialog first')
  await expect(help).toContainText('E: nearby action keyboard fallback')
  await page.keyboard.press('d'); await page.clock.runFor(500)
  await help.hover(); await page.mouse.wheel(0, -300); await page.clock.runFor(64)
  await expect(scene(page)).toHaveAttribute('data-camera-scale', '26')
  expect(await positionIn(page, 'ship:scout')).toEqual(start)
  await page.screenshot({ path: info.outputPath('help.png') })
  await page.keyboard.press('Escape'); await expect(help).not.toBeVisible()
  await page.getByRole('button', { name: 'Equip gathering tool' }).click()
  for (const interrupt of ['cancel', 'hidden', 'resize']) {
    await choose(page, source, 'Gather / Mine')
    await expect(receipt(page)).toHaveAttribute('data-command-status', 'approaching')
    if (interrupt === 'cancel') await page.getByRole('button', { name: 'Cancel command' }).click()
    if (interrupt === 'hidden') await page.evaluate(() => {
      Object.defineProperty(document, 'hidden', { configurable: true, get: () => true })
      document.dispatchEvent(new Event('visibilitychange'))
    })
    if (interrupt === 'resize') await page.setViewportSize({ width: 1100, height: 760 })
    await page.clock.runFor(500)
    const held = await positionIn(page, 'ship:scout')
    await page.clock.runFor(1000)
    expect(await positionIn(page, 'ship:scout')).toEqual(held)
    await expect(receipt(page)).toHaveAttribute('data-command-status', 'cancelled')
    await expect(page.getByLabel('Resource inventory')).toHaveAttribute('data-gathering', '')
    if (interrupt === 'hidden') await page.evaluate(() => { delete (document as unknown as { hidden?: boolean }).hidden; document.dispatchEvent(new Event('visibilitychange')) })
  }
  const inventory = page.getByRole('button', { name: /Field inventory/ })
  await inventory.click()
  const held = await positionIn(page, 'ship:scout'), scale = await scene(page).getAttribute('data-camera-scale')
  await page.locator('#field-inventory').click({ button: 'right' })
  await page.locator('#field-inventory').hover(); await page.mouse.wheel(0, -400)
  await page.keyboard.press('d'); await page.clock.runFor(500)
  expect(await positionIn(page, 'ship:scout')).toEqual(held)
  await expect(scene(page)).toHaveAttribute('data-camera-scale', scale!)
  await expect(page.getByRole('menu')).toHaveCount(0)
  await page.keyboard.press('Escape'); await expect(inventory).toHaveAttribute('aria-expanded', 'false')
  // Actual E fallback after a mouse approach still uses the same domain action.
  await choose(page, 'scout:storage', 'Use Resource Container'); await finish(page)
  const panel = page.getByRole('dialog', { name: 'Resource Container', exact: true })
  await panel.getByRole('textbox', { name: 'Amount in grams' }).fill('wasd e')
  await page.keyboard.press('Space'); await page.clock.runFor(100)
  const panelPosition = await positionIn(page, 'ship:scout')
  await page.keyboard.press('Escape'); await page.clock.runFor(32)
  await scene(page).focus(); await page.keyboard.press('e'); await page.clock.runFor(32)
  await expect(panel).toBeVisible()
  expect(await positionIn(page, 'ship:scout')).toEqual(panelPosition)
  await page.screenshot({ path: info.outputPath('keyboard-container.png') })
})

test('UX-894 built unavailable mining, active Cancel and full-inventory feedback', async ({ page }, info) => {
  await boot(page, '', 'http://127.0.0.1:4175')
  const p = await point(page, source)
  await page.mouse.click(p.x, p.y, { button: 'right' })
  const mine = page.getByRole('menuitem', { name: /Gather \/ Mine/ })
  await expect(mine).toHaveAttribute('aria-disabled', 'true')
  await expect(mine).toContainText('Equip the gathering tool first')
  const held = await positionIn(page, 'ship:scout')
  await mine.click(); await page.clock.runFor(500)
  expect(await positionIn(page, 'ship:scout')).toEqual(held)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Equip gathering tool' }).click()
  await choose(page, source, 'Gather / Mine'); await finish(page)
  await walkTicks(page, [], 60)
  await page.getByRole('button', { name: 'Cancel command' }).click()
  await expect(receipt(page)).toContainText('Mining cancelled')
  const cancelled = await saved(page)
  await page.clock.runFor(1000)
  expect((await saved(page)).inventory).toEqual(cancelled.inventory)
  await choose(page, source, 'Gather / Mine'); await finish(page)
  // Run actual work until the domain capacity rule ends it; no save injection.
  await walkTicks(page, [], 540)
  await expect(page.locator('[data-inventory-weight]')).toHaveText('10 / 10 kg')
  await page.clock.runFor(1000)
  await expect(page.getByLabel('Resource inventory')).toHaveAttribute('data-gathering', '')
  await expect(receipt(page)).toContainText('Inventory full')
  const full = await saved(page)
  const q = await point(page, source)
  await page.mouse.click(q.x, q.y, { button: 'right' })
  await expect(mine).toHaveAttribute('aria-disabled', 'true')
  await expect(mine).toContainText('Inventory full: weight limit')
  await mine.click(); await page.clock.runFor(500)
  expect((await saved(page)).inventory).toEqual(full.inventory)
  await page.screenshot({ path: info.outputPath('inventory-full.png') })
  await info.attach('capacity-state.json', { body: JSON.stringify({ cancelled, full, afterUnavailable: await saved(page) }), contentType: 'application/json' })
})
